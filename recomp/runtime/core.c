/* Boot, dispatch of indirect calls, syscalls. */
#include <stdlib.h>
#include "hw.h"

Options opt = { .widescreen = 1, .scale = 3, .fps_unlock = 0, .vsync = 1, .fps = 60, .overclock = 1,
                .fixed_timestep = 1, .volume = 100 };

static rt_func lookup(uint32_t a) {
    int lo = 0, hi = rt_func_count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        uint32_t m = rt_func_table[mid].addr;
        if (m == a) return rt_func_table[mid].fn;
        if (m < a) lo = mid + 1; else hi = mid - 1;
    }
    return 0;
}

void rt_dispatch(uint32_t target) {
    uint32_t phys = target & 0x1FFFFFFF;
    if (phys == 0xA0 || phys == 0xB0 || phys == 0xC0) {
        bios_call(phys, cpu.r[9]);
        return;
    }
    rt_func f = lookup(0x80000000u | phys);
    if (!f) rt_fatal("dispatch to unknown code address %08x (ra=%08x)", target, cpu.r[31]);
    f();
}

void rt_syscall(uint32_t pc) {
    uint32_t fn = cpu.r[4];
    switch (fn) {
    case 1: /* EnterCriticalSection */
        cpu.r[2] = (cpu.sr & 0x401) == 0x401;
        cpu.sr &= ~0x401u;
        break;
    case 2: /* ExitCriticalSection */
        cpu.sr |= 0x401;
        break;
    case 0:
    case 3:
        break;
    default:
        rt_logf("syscall %u at %08x\n", fn, pc);
        break;
    }
    sched_update();
    irq_check();
}

void rt_break(uint32_t pc) {
    rt_logf("break at %08x (a0=%08x)\n", pc, cpu.r[4]);
    if (pc == 0x80021948u) { /* the game's MemAlloc failure: its message is in 0x800C4E78 */
        char m[160];
        int i = 0;
        for (; i < (int)sizeof m - 1; i++) { m[i] = (char)mem_r8(0x800C4E78u + (uint32_t)i); if (!m[i]) break; }
        m[i] = 0;
        rt_logf("game message: %s(MemAlloc called from %08x, file id %u)\n", m, mem_r32(cpu.r[29] + 0x24u),
                mem_r32(cpu.r[29] + 0x1cu));
    }
}

void rt_invalid(uint32_t pc) {
    rt_fatal("executed invalid / data word at %08x", pc);
}

void rt_fallthrough_error(uint32_t pc) {
    rt_fatal("fell through to unrecompiled address %08x", pc);
}

/* generated by recomp.py */
extern const unsigned char game_exe[];
extern const unsigned int game_exe_size;

#include "savestate.h"
static uint32_t boot_pc;
static void boot_start(void) { rt_dispatch(boot_pc); }

void rt_boot(void) {
    uint32_t pc0, gp, taddr, tsize, sp;
    memcpy(&pc0, game_exe + 16, 4);
    memcpy(&gp, game_exe + 20, 4);
    memcpy(&taddr, game_exe + 24, 4);
    memcpy(&tsize, game_exe + 28, 4);
    memcpy(&sp, game_exe + 48, 4);
    memcpy(ram + (taddr & 0x1FFFFF), game_exe + 0x800, tsize);
    { void mods_boot(void); mods_boot(); }   /* mods.c: replaced disc files -> the game's file tables */
    memset(&cpu, 0, sizeof cpu);
    cpu.r[29] = cpu.r[30] = sp ? sp : 0x801FFFF0;
    cpu.r[28] = gp;
    cpu.sr = 0x40000000;
    cpu.next_event = 0;
    clk_mul = opt.overclock < 1 ? 1 : (uint32_t)opt.overclock;
    sched(EV_VBLANK, CYCLES_PER_FRAME);
    void present_start(void);
    present_start();
    rt_logf("video: %d fps, virtual CPU x%u, real-time game step %s\n", opt.fps, clk_mul,
            opt.fixed_timestep ? "on" : "off");
    rt_logf("boot: entry %08x load %08x+%x sp %08x\n", pc0, taddr, tsize, sp);
    cpu.r[31] = 0;
    boot_pc = pc0;
    state_boot(boot_start); /* a quick load restarts the guest from inside state_boot */
    rt_logf("game main returned\n");
}
